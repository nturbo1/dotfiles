return function(hl, c)
    hl("Keyword",       { fg = c.keyword, bold = true })
    hl("String",        { fg = c.string })
    hl("Comment",       { fg = c.comment, italic = true })
    hl("Constant",      { fg = c.constant })
    hl("Function",      { fg = c.function_ })
    hl("Identifier",    { fg = c.text })
    hl("Type",          { fg = c.type })
    hl("Statement",     { fg = c.text })
    hl("PreProc",       { fg = c.text })
    hl("Special",       { fg = c.text })
    hl("Number",        { fg = c.number })
    hl("Operator",      { fg = c.operator })
    hl("Punctuation",   { fg = c.punctuation })
    hl("Delimiter",     { fg = c.text })
    hl("ModeMsg",       { fg = "#BBB529" })
    hl("Boolean",       { fg = c.boolean })
end
